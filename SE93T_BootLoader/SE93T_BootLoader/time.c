/******************************************************************************
* 函数名称: delayms()
* 功能描述: 毫秒延时程序
* 输入参数: 延时时间
* 输出参数: 无
* 说    明: 单位：1ms；最大：255ms
******************************************************************************/
void delayms(unsigned char time)
{
    unsigned int i;

    do
    {
        i=1000;
        while(--i);
    }
    while(--time);
}
