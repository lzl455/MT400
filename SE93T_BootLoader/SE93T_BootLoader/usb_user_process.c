/******************************************************************************
* 函数名称: usb_data_process()
* 功能描述: USB数据发送处理
* 输入参数: 无
* 输出参数: 无
* 说    明: USB数据发送处理
******************************************************************************/
void usb_data_process(void)
{
    unsigned char* pReg;

    if(bhid_data_send && !bEp1Busy)
    {
        bEp1Busy = 1;
        pReg = EP1IOPS_ADDR;                    // EPxIOPS地址
        *pReg++ = 32;                           // 包大小
		memcpy(UsbEp1Buffer, in_report_data, 32);

        *pReg = 1;                              // 开始传输
        bhid_data_send = 0;
    }
}
