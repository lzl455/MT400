/******************************************************************************
* 函数名称: led_mode_snake
* 功能描述:
* 输入参数: 无
* 输出参数: 无
* 说    明:
******************************************************************************/
void led_mode_single(void)
{
    unsigned char i;

    if(led_speed_lev>delay_time_count)
    {
		delay_time_count++;
        return;
	}
    delay_time_count = 0;

    for(i=0; i<iLED_ALL_MAX; i++)
    {
        if(0 != pwm_duty_array[i])
        {
            pwm_duty_array[i]--;
        }
    }
}

